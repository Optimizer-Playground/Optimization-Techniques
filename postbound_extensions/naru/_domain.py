class ColumnKind(enum.Enum):
    """The value semantics of a column, as far as Naru is concerned."""

    Numeric = "numeric"
    Temporal = "temporal"
    Text = "text"
    Boolean = "boolean"


def column_kind(dtype: str) -> ColumnKind | None:
    """Maps a (Postgres or DuckDB) data type to the corresponding column kind.

    Returns *None* for data types that Naru cannot model (e.g. arrays or JSON).
    """
    dtype = dtype.lower().strip()
    base_type = dtype.split("(")[0].strip()
    match base_type:
        case (
            "smallint"
            | "integer"
            | "int"
            | "int2"
            | "int4"
            | "int8"
            | "bigint"
            | "hugeint"
            | "tinyint"
            | "utinyint"
            | "usmallint"
            | "uinteger"
            | "ubigint"
            | "real"
            | "float"
            | "float4"
            | "float8"
            | "double"
            | "double precision"
            | "numeric"
            | "decimal"
        ):
            return ColumnKind.Numeric
        case (
            "timestamp"
            | "timestamp without time zone"
            | "timestamp with time zone"
            | "timestamptz"
            | "datetime"
            | "date"
        ):
            return ColumnKind.Temporal
        case "character varying" | "varchar" | "text" | "character" | "char" | "bpchar" | "string":
            return ColumnKind.Text
        case "boolean" | "bool":
            return ColumnKind.Boolean
        case _:
            return None


def _to_numpy(values: Iterable[Any], kind: ColumnKind) -> np.ndarray:
    """Converts raw (non-NULL) values as returned by the database into a numpy array with a comparable dtype."""
    values = list(values)
    match kind:
        case ColumnKind.Numeric:
            if values and all(isinstance(v, int) and not isinstance(v, bool) for v in values):
                return np.asarray(values, dtype=np.int64)
            return np.asarray([float(v) for v in values], dtype=np.float64)
        case ColumnKind.Temporal:
            return np.asarray([_to_datetime64(v) for v in values], dtype="datetime64[us]")
        case ColumnKind.Text:
            arr = np.empty(len(values), dtype=object)
            arr[:] = [str(v) for v in values]
            return arr
        case ColumnKind.Boolean:
            return np.asarray([bool(v) for v in values], dtype=np.int64)


def _to_datetime64(value: Any) -> np.datetime64:
    match value:
        case np.datetime64():
            return value.astype("datetime64[us]")
        case datetime() if value.tzinfo is not None:
            return np.datetime64(pd.Timestamp(value).tz_convert(None).to_datetime64(), "us")
        case datetime() | date():
            return np.datetime64(value, "us")
        case str():
            return np.datetime64(pd.Timestamp(value).tz_localize(None).to_datetime64(), "us")
        case _:
            raise TypeError(f"Cannot interpret {value!r} ({type(value).__name__}) as a date or timestamp")


def _like_regex(pattern: str, *, case_insensitive: bool) -> re.Pattern:
    """Translates an SQL LIKE pattern into an equivalent regular expression."""
    regex_parts: list[str] = []
    escaped = False
    for char in pattern:
        if escaped:
            regex_parts.append(re.escape(char))
            escaped = False
        elif char == "\\":
            escaped = True
        elif char == "%":
            regex_parts.append(".*")
        elif char == "_":
            regex_parts.append(".")
        else:
            regex_parts.append(re.escape(char))
    flags = re.DOTALL | (re.IGNORECASE if case_insensitive else 0)
    return re.compile("".join(regex_parts), flags)


class UnsupportedPredicateError(ValueError):
    """Indicates that Naru cannot evaluate a specific (part of a) predicate."""


@dataclass(frozen=True)
class ValueSet:
    """A set of values of a single column, represented as a mask over the distinct values of its domain.

    Attributes
    ----------
    mask : np.ndarray
        Boolean mask over the distinct (non-NULL) values of the domain.
    null : bool
        Whether the NULL value is part of the set.
    """

    mask: np.ndarray
    null: bool

    def intersect(self, other: ValueSet) -> ValueSet:
        return ValueSet(self.mask & other.mask, self.null and other.null)

    def is_empty(self) -> bool:
        return not self.null and not self.mask.any()

    def is_full(self) -> bool:
        return self.null and bool(self.mask.all())

    def key(self) -> tuple[bytes, bool]:
        """Hashable representation of the value set."""
        return np.packbits(self.mask).tobytes(), self.null


@dataclass(frozen=True)
class TruthMask:
    """The result of evaluating a predicate on all values of a column, following SQL's three-valued logic.

    Each value can make the predicate *true*, *false*, or *unknown* (which is the case if neither flag is set).
    Only the NULL value can lead to unknown results, since we only support predicates with static values.
    """

    true: ValueSet
    false: ValueSet

    def negate(self) -> TruthMask:
        return TruthMask(true=self.false, false=self.true)

    def conjunction(self, other: TruthMask) -> TruthMask:
        true = ValueSet(self.true.mask & other.true.mask, self.true.null and other.true.null)
        false = ValueSet(self.false.mask | other.false.mask, self.false.null or other.false.null)
        return TruthMask(true=true, false=false)

    def disjunction(self, other: TruthMask) -> TruthMask:
        true = ValueSet(self.true.mask | other.true.mask, self.true.null or other.true.null)
        false = ValueSet(self.false.mask & other.false.mask, self.false.null and other.false.null)
        return TruthMask(true=true, false=false)


class ColumnDomain:
    """The domain of a single column, i.e. all its distinct values and their frequencies.

    The domain implements Naru's dictionary encoding (Section 4.2 of the paper): all distinct values of the column are
    sorted and each value is mapped to an integer token in *[0, |domain|)*. If the column contains NULL values, these
    are represented by a dedicated token 0.

    For columns with very large domains (e.g. timestamps or primary keys), the exact dictionary leads to huge output
    layers and slow training. Therefore, the domain can be *bucketized*: the sorted values are partitioned into
    equi-depth buckets and each bucket becomes a token. Since the domain still knows the exact frequency of each
    value, a predicate can be translated into a per-bucket weight: the fraction of the bucket's rows that satisfy the
    predicate. This is the only approximation that bucketization introduces: within a bucket, we assume that the
    predicate is independent of all other columns. For non-bucketized domains, all weights are either 0 or 1 and we
    obtain the original Naru behavior.

    Use `fetch` to compute the domain of a column directly from the database.

    Parameters
    ----------
    column : pb.ColumnReference
        The column. Must be bound to its table.
    dtype : str
        The data type of the column in the database.
    values : np.ndarray
        The sorted distinct non-NULL values of the column.
    counts : np.ndarray
        The number of occurrences of each value.
    null_count : int
        The number of NULL values in the column.
    max_tokens : int | None, optional
        If the number of distinct values exceeds this threshold, the domain is bucketized into roughly `max_tokens`
        equi-depth buckets. If *None*, the domain is never bucketized.
    """

    @staticmethod
    def fetch(
        column: pb.ColumnReference,
        *,
        database: pb.Database,
        max_tokens: int | None = None,
        verbose: bool | pb.util.Logger = False,
    ) -> ColumnDomain:
        """Computes the domain of a column based on the current database contents.

        All data is fetched via `pb.db.PreciseStatistics`, i.e. the domain is exact.
        """
        log = wrap_logger(verbose)
        if not pb.ColumnReference.assert_bound(column):
            raise pb.UnboundColumnError(column)

        dtype = database.schema().datatype(column)
        kind = column_kind(dtype)
        if kind is None:
            raise TypeError(f"Unsupported data type '{dtype}' for column {column}")

        log("Fetching domain of", column)
        stats = pb.db.PreciseStatistics(database)
        n_rows = int(stats.total_rows(column.table).value)
        frequencies = stats.most_common_values(column, k=-1)
        raw_values = list(frequencies.values)
        raw_counts = list(frequencies.frequencies)

        values = _to_numpy(raw_values, kind)
        counts = np.asarray(raw_counts, dtype=np.int64)
        sort_idx = np.argsort(values, kind="stable")
        values, counts = values[sort_idx], counts[sort_idx]

        if len(values) > 1 and (values[1:] == values[:-1]).any():
            # This can happen if multiple raw values are mapped to the same numpy value, e.g. timestamps with
            # different time zones. We merge such values.
            values, inverse = np.unique(values, return_inverse=True)
            counts = np.bincount(inverse, weights=counts).astype(np.int64)

        null_count = n_rows - int(counts.sum())
        return ColumnDomain(column, dtype, values=values, counts=counts, null_count=null_count, max_tokens=max_tokens)

    @staticmethod
    def load(
        column: pb.ColumnReference, *, dtype: str, archive: Path, null_count: int, max_tokens: int | None
    ) -> ColumnDomain:
        """Loads a domain that was previously persisted with `store`."""
        df = pd.read_parquet(archive)
        kind = column_kind(dtype)
        assert kind is not None
        values = df["value"].to_numpy()
        match kind:
            case ColumnKind.Temporal:
                values = values.astype("datetime64[us]")
            case ColumnKind.Text:
                values = values.astype(object)
            case _:
                pass
        counts = df["count"].to_numpy().astype(np.int64)
        return ColumnDomain(column, dtype, values=values, counts=counts, null_count=null_count, max_tokens=max_tokens)

    def __init__(
        self,
        column: pb.ColumnReference,
        dtype: str,
        *,
        values: np.ndarray,
        counts: np.ndarray,
        null_count: int,
        max_tokens: int | None = None,
    ) -> None:
        if not pb.ColumnReference.assert_bound(column):
            raise pb.UnboundColumnError(column)
        kind = column_kind(dtype)
        if kind is None:
            raise TypeError(f"Unsupported data type '{dtype}' for column {column}")

        self.column: pb.BoundColumnReference = column
        self.dtype = dtype
        self.kind = kind
        self.values = values
        self.counts = counts
        self.null_count = int(null_count)
        self.max_tokens = max_tokens

        self.null_offset = 1 if self.null_count > 0 else 0
        if max_tokens is not None and len(values) > max_tokens:
            self.bucket_of: np.ndarray | None = _equi_depth_buckets(counts, max_tokens)
            self.n_buckets = int(self.bucket_of[-1]) + 1 if len(self.bucket_of) else 0
            self._bucket_totals = np.bincount(self.bucket_of, weights=counts, minlength=self.n_buckets)
        else:
            self.bucket_of = None
            self.n_buckets = len(values)
            self._bucket_totals = counts.astype(np.float64)

    @property
    def n_distinct(self) -> int:
        """The number of distinct non-NULL values."""
        return len(self.values)

    @property
    def n_tokens(self) -> int:
        """The number of tokens (i.e. the size of the dictionary, including the NULL token)."""
        return max(1, self.null_offset + self.n_buckets)

    @property
    def n_rows(self) -> int:
        return int(self.counts.sum()) + self.null_count

    @property
    def is_bucketized(self) -> bool:
        return self.bucket_of is not None

    def token_frequencies(self) -> np.ndarray:
        """The number of rows that are mapped to each token."""
        freqs = np.zeros(self.n_tokens, dtype=np.float64)
        if self.null_offset:
            freqs[0] = self.null_count
        freqs[self.null_offset : self.null_offset + self.n_buckets] = self._bucket_totals
        return freqs

    def tokenize(self, raw_values: Sequence[Any]) -> np.ndarray:
        """Maps raw column values (as returned by the database) to their tokens."""
        raw_values = list(raw_values)
        tokens = np.zeros(len(raw_values), dtype=np.int64)
        not_null = np.fromiter((v is not None for v in raw_values), dtype=bool, count=len(raw_values))
        if not not_null.any():
            return tokens

        if not self.n_distinct:
            raise ValueError(f"Column {self.column} has a non-NULL value, but its domain is empty")

        converted = _to_numpy([v for v in raw_values if v is not None], self.kind)
        idx = np.searchsorted(self.values, converted)
        idx = np.clip(idx, 0, len(self.values) - 1)
        mismatches = self.values[idx] != converted
        if mismatches.any():
            raise ValueError(
                f"Column {self.column} contains values that are not part of its domain, e.g. "
                f"{converted[mismatches][0]!r}. The domain is probably outdated."
            )

        if self.bucket_of is not None:
            idx = self.bucket_of[idx]
        tokens[not_null] = idx + self.null_offset
        return tokens

    def token_weights(self, values: ValueSet) -> np.ndarray:
        """Computes the fraction of each token's rows that are contained in a value set.

        For exact domains, the weights are 1 for all tokens whose value is part of the set and 0 otherwise. For
        bucketized domains, the weight of each bucket is the fraction of its rows that are part of the set.
        """
        weights = np.zeros(self.n_tokens, dtype=np.float32)
        if self.null_offset:
            weights[0] = 1.0 if values.null else 0.0
        if self.bucket_of is None:
            weights[self.null_offset : self.null_offset + self.n_buckets] = values.mask
        else:
            selected = np.bincount(self.bucket_of, weights=self.counts * values.mask, minlength=self.n_buckets)
            weights[self.null_offset : self.null_offset + self.n_buckets] = selected / self._bucket_totals
        return weights

    def full(self) -> ValueSet:
        return ValueSet(np.ones(self.n_distinct, dtype=bool), True)

    def empty(self) -> ValueSet:
        return ValueSet(np.zeros(self.n_distinct, dtype=bool), False)

    def evaluate(self, predicate: pb.qal.SimpleFilter) -> TruthMask:
        """Evaluates a simple filter predicate on all values of the domain.

        Raises
        ------
        UnsupportedPredicateError
            If the predicate cannot be evaluated, e.g. because the operator is unsupported or the filter value cannot
            be compared with the column values.
        """
        op, raw_value = predicate.operator, predicate.value
        n = self.n_distinct
        no_values = np.zeros(n, dtype=bool)

        match op:
            case pb.qal.UnaryOperator.IsNull:
                return TruthMask(ValueSet(no_values, True), ValueSet(~no_values, False))
            case pb.qal.UnaryOperator.IsNotNull:
                return TruthMask(ValueSet(~no_values, False), ValueSet(no_values, True))
            case pb.qal.UnaryOperator.IsTrue | pb.qal.UnaryOperator.IsNotTrue:
                is_true = self._compare(operator.eq, True)
                truth = TruthMask(ValueSet(is_true, False), ValueSet(~is_true, True))
                return truth if op == pb.qal.UnaryOperator.IsTrue else truth.negate()
            case pb.qal.UnaryOperator.IsFalse | pb.qal.UnaryOperator.IsNotFalse:
                is_false = self._compare(operator.eq, False)
                truth = TruthMask(ValueSet(is_false, False), ValueSet(~is_false, True))
                return truth if op == pb.qal.UnaryOperator.IsFalse else truth.negate()
            case pb.qal.BinaryOperator.NotDistinctFrom | pb.qal.BinaryOperator.DistinctFrom:
                matches = no_values if raw_value is None else self._compare(operator.eq, raw_value)
                truth = TruthMask(ValueSet(matches, raw_value is None), ValueSet(~matches, raw_value is not None))
                return truth if op == pb.qal.BinaryOperator.NotDistinctFrom else truth.negate()
            case pb.qal.UnaryOperator.Exists:
                raise UnsupportedPredicateError(f"Unsupported predicate {predicate}")

        # All remaining operators follow the usual SQL semantics: comparisons with NULL are unknown.
        match op:
            case pb.qal.BinaryOperator.In | pb.qal.BinaryOperator.NotIn:
                literals = [v for v in raw_value if v is not None]
                has_null_literal = len(literals) < len(raw_value)
                matches = np.zeros(n, dtype=bool)
                for literal in literals:
                    matches |= self._compare(operator.eq, literal)
                if op == pb.qal.BinaryOperator.In:
                    return self._truth(true=matches, false=~matches)
                # x NOT IN (..., NULL) is never true
                return self._truth(true=no_values if has_null_literal else ~matches, false=matches)

            case pb.qal.BinaryOperator.Between:
                lower, upper = raw_value
                if lower is None or upper is None:
                    return self._truth(true=no_values, false=no_values)
                matches = self._compare(operator.ge, lower) & self._compare(operator.le, upper)
                return self._truth(true=matches, false=~matches)

        if raw_value is None:
            # comparison with NULL literal is always unknown
            return self._truth(true=no_values, false=no_values)

        match op:
            case pb.qal.BinaryOperator.Equal:
                matches = self._compare(operator.eq, raw_value)
            case pb.qal.BinaryOperator.NotEqual:
                matches = ~self._compare(operator.eq, raw_value)
            case pb.qal.BinaryOperator.Less:
                matches = self._compare(operator.lt, raw_value)
            case pb.qal.BinaryOperator.LessEqual:
                matches = self._compare(operator.le, raw_value)
            case pb.qal.BinaryOperator.Greater:
                matches = self._compare(operator.gt, raw_value)
            case pb.qal.BinaryOperator.GreaterEqual:
                matches = self._compare(operator.ge, raw_value)
            case pb.qal.BinaryOperator.Like | pb.qal.BinaryOperator.NotLike:
                matches = self._like(raw_value, case_insensitive=False)
                matches = matches if op == pb.qal.BinaryOperator.Like else ~matches
            case pb.qal.BinaryOperator.ILike | pb.qal.BinaryOperator.NotILike:
                matches = self._like(raw_value, case_insensitive=True)
                matches = matches if op == pb.qal.BinaryOperator.ILike else ~matches
            case _:
                raise UnsupportedPredicateError(f"Unsupported operator {op} in predicate {predicate}")

        return self._truth(true=matches, false=~matches)

    def store(self, archive: Path) -> Path:
        """Persists the distinct values and their frequencies as a Parquet file."""
        archive.parent.mkdir(parents=True, exist_ok=True)
        df = pd.DataFrame({"value": self.values, "count": self.counts})
        df.to_parquet(archive, index=False)
        return archive

    def __json__(self) -> pb.util.jsondict:
        return {
            "column": self.column,
            "dtype": self.dtype,
            "n_distinct": self.n_distinct,
            "null_count": self.null_count,
            "n_tokens": self.n_tokens,
            "bucketized": self.is_bucketized,
        }

    @override
    def __repr__(self) -> str:
        bucketized = f", buckets={self.n_buckets}" if self.is_bucketized else ""
        return f"ColumnDomain({self.column}, dtype={self.dtype}, distinct={self.n_distinct}{bucketized})"

    def _truth(self, *, true: np.ndarray, false: np.ndarray) -> TruthMask:
        # NULL never satisfies (or violates) a comparison, it is always unknown
        return TruthMask(ValueSet(true, False), ValueSet(false, False))

    def _coerce(self, value: Any) -> Any:
        """Converts a filter literal into a value that can be compared with the domain values."""
        try:
            match self.kind:
                case ColumnKind.Numeric:
                    match value:
                        case bool():
                            return int(value)
                        case int() | float():
                            return value
                        case Decimal():
                            return float(value)
                        case str():
                            return float(value)
                        case _:
                            raise UnsupportedPredicateError(
                                f"Cannot compare {value!r} with numeric column {self.column}"
                            )
                case ColumnKind.Temporal:
                    return _to_datetime64(value)
                case ColumnKind.Text:
                    return str(value)
                case ColumnKind.Boolean:
                    match value:
                        case bool() | int():
                            return int(bool(value))
                        case str() if value.lower() in {"t", "true", "1", "yes", "y", "on"}:
                            return 1
                        case str() if value.lower() in {"f", "false", "0", "no", "n", "off"}:
                            return 0
                        case _:
                            raise UnsupportedPredicateError(
                                f"Cannot compare {value!r} with boolean column {self.column}"
                            )
        except (TypeError, ValueError) as e:
            raise UnsupportedPredicateError(f"Cannot compare {value!r} with column {self.column}") from e

    def _compare(self, op: Callable[[Any, Any], Any], value: Any) -> np.ndarray:
        if not self.n_distinct:
            return np.zeros(0, dtype=bool)
        literal = self._coerce(value)
        # numpy evaluates comparisons element-wise, including object arrays of strings
        return np.asarray(op(self.values, literal), dtype=bool)

    def _like(self, pattern: Any, *, case_insensitive: bool) -> np.ndarray:
        if self.kind != ColumnKind.Text or not isinstance(pattern, str):
            raise UnsupportedPredicateError(f"LIKE predicates are only supported on text columns, not on {self.column}")
        regex = _like_regex(pattern, case_insensitive=case_insensitive)
        return np.fromiter((regex.fullmatch(v) is not None for v in self.values), dtype=bool, count=self.n_distinct)


def _equi_depth_buckets(counts: np.ndarray, n_buckets: int) -> np.ndarray:
    """Assigns sorted values with the given frequencies to (roughly) equi-depth buckets.

    Values are never split across buckets. Very frequent values occupy a bucket on their own, which is why the actual
    number of buckets can be smaller than requested. The returned array contains consecutive bucket ids starting at 0.
    """
    if not len(counts):
        return np.zeros(0, dtype=np.int64)
    total = counts.sum()
    preceding = np.cumsum(counts) - counts
    raw_ids = np.floor(preceding / total * n_buckets).astype(np.int64)
    _, bucket_ids = np.unique(raw_ids, return_inverse=True)
    return bucket_ids.astype(np.int64)
