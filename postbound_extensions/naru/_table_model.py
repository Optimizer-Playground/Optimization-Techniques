def _file_name(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]", "_", name)


class NaruTableModel:
    """A Naru estimator for a single table.

    The model consists of the dictionary encodings (`ColumnDomain`) of all modeled columns and a deep autoregressive
    model (`MADE`) that approximates the joint distribution of these columns. Selectivities are computed using
    progressive sampling.

    Use `build` to create and train a new model based on the database contents.

    Parameters
    ----------
    table : pb.TableReference
        The modeled table (without alias).
    domains : Sequence[ColumnDomain]
        The domains of the modeled columns. Their order is the natural column order of the model.
    row_count : int
        The number of rows in the table.
    hyper_params : NaruHyperParams
        Hyperparameters of the model.
    model : MADE | None, optional
        A (pre-trained) autoregressive model. If omitted, the model has to be trained via `fit` before it can be used.
    training_metrics : dict | None, optional
        Metrics of the training process that produced the model.
    verbose : bool | pb.util.Logger, optional
        Whether to log progress information.
    """

    @staticmethod
    def build(
        table: pb.TableReference,
        columns: Sequence[pb.ColumnReference],
        *,
        database: pb.Database,
        hyper_params: NaruHyperParams,
        verbose: bool | pb.util.Logger = False,
    ) -> NaruTableModel:
        """Creates and trains a new model for specific columns of a table."""
        log = wrap_logger(verbose)
        log("Building Naru model for table", table, "on columns", [col.name for col in columns])
        stats = pb.db.PreciseStatistics(database)
        row_count = int(stats.total_rows(table).value)
        domains = [
            ColumnDomain.fetch(col, database=database, max_tokens=hyper_params.max_domain_size, verbose=verbose)
            for col in columns
        ]
        model = NaruTableModel(table, domains, row_count=row_count, hyper_params=hyper_params, verbose=verbose)
        model.fit(database)
        return model

    @staticmethod
    def load(
        catalog_entry: dict[str, Any],
        *,
        directory: Path,
        hyper_params: NaruHyperParams,
        verbose: bool | pb.util.Logger = False,
    ) -> NaruTableModel:
        """Re-creates a model that was persisted using `store`.

        Parameters
        ----------
        catalog_entry : dict[str, Any]
            The catalog entry that was returned by `store`.
        directory : Path
            The directory relative to which the domain and model files are resolved.
        hyper_params : NaruHyperParams
            The hyperparameters that were used to build the model.
        verbose : bool | pb.util.Logger, optional
            Whether to log progress information.
        """
        log = wrap_logger(verbose)
        table = pb.parser.load_table_json(catalog_entry["table"])
        assert table is not None
        log("Loading Naru model for table", table)

        domains: list[ColumnDomain] = []
        for col_entry in catalog_entry["columns"]:
            column = pb.parser.load_column_json(col_entry["column"])
            assert column is not None
            domains.append(
                ColumnDomain.load(
                    column,
                    dtype=col_entry["dtype"],
                    archive=directory / col_entry["domain_file"],
                    null_count=col_entry["null_count"],
                    max_tokens=hyper_params.max_domain_size,
                )
            )

        made: MADE | None = None
        if catalog_entry.get("model_file"):
            made = NaruTableModel._create_made(domains, hyper_params, ordering=catalog_entry["ordering"])
            weights = torch.load(directory / catalog_entry["model_file"], map_location="cpu", weights_only=True)
            made.load_state_dict(weights)

        return NaruTableModel(
            table,
            domains,
            row_count=catalog_entry["row_count"],
            hyper_params=hyper_params,
            model=made,
            training_metrics=catalog_entry.get("training_metrics"),
            verbose=verbose,
        )

    def __init__(
        self,
        table: pb.TableReference,
        domains: Sequence[ColumnDomain],
        *,
        row_count: int,
        hyper_params: NaruHyperParams,
        model: MADE | None = None,
        training_metrics: dict | None = None,
        verbose: bool | pb.util.Logger = False,
    ) -> None:
        self.table = table.drop_alias()
        self.domains = list(domains)
        self.row_count = int(row_count)
        self.hyper_params = hyper_params
        self._log = wrap_logger(verbose)
        self._device = hyper_params.resolve_device()
        self._column_index = {domain.column.name.lower(): i for i, domain in enumerate(self.domains)}

        self.model = model.to(self._device).eval() if model is not None else None
        self.training_metrics: dict = training_metrics or {"status": "untrained"}

    @property
    def columns(self) -> list[pb.ColumnReference]:
        return [domain.column for domain in self.domains]

    @property
    def ordering(self) -> list[int]:
        """The autoregressive column ordering as a list of column indices."""
        if self.model is None:
            return list(range(len(self.domains)))
        return list(self.model.ordering)

    def is_trained(self) -> bool:
        return not self.domains or self.model is not None

    def models_column(self, column: pb.ColumnReference) -> bool:
        return column.name.lower() in self._column_index

    def fetch_training_data(self, database: pb.Database) -> np.ndarray:
        """Loads the (dictionary-encoded) training data from the database.

        If the table has more than `max_training_rows` rows, a uniform sample is used.

        Returns
        -------
        np.ndarray
            The encoded tuples of shape [n_rows, n_columns].
        """
        select_clause = Select([Projection.column(col) for col in self.columns])
        from_clause = pb.qal.From.create_for(self.table)
        max_rows = self.hyper_params.max_training_rows
        if max_rows is not None and self.row_count > max_rows:
            self._log(f"Sampling {max_rows} rows from table {self.table} for training")
            order_clause = OrderBy([Ordering(FunctionExpression("random", []))])
            query = as_query(select_clause, from_clause, order_clause, Limit(limit=max_rows))
        else:
            query = as_query(select_clause, from_clause)

        self._log("Fetching training data for table", self.table)
        rows = database.execute_query(query, raw=True)
        if not rows:
            return np.zeros((0, len(self.domains)), dtype=np.int64)

        raw_columns = list(zip(*rows))
        tokens = [domain.tokenize(raw_col) for domain, raw_col in zip(self.domains, raw_columns)]
        return np.stack(tokens, axis=1)

    def fit(self, data: pb.Database | np.ndarray) -> dict:
        """Trains the model by maximizing the likelihood of the table's tuples.

        Parameters
        ----------
        data : pb.Database | np.ndarray
            Either the database from which the training data should be loaded, or pre-encoded tuples (see
            `fetch_training_data`).

        Returns
        -------
        dict
            The training metrics. These are also available via the `training_metrics` attribute.
        """
        if not self.domains:
            self.training_metrics = {"status": "completed", "n_columns": 0}
            return self.training_metrics

        tokens = self.fetch_training_data(data) if isinstance(data, pb.Database) else np.asarray(data, dtype=np.int64)
        if not len(tokens):
            raise ValueError(f"Cannot train a Naru model for table {self.table}: no training data")

        params = self.hyper_params
        start_time = time.perf_counter()
        ordering = compute_ordering(params.ordering, tokens, seed=params.seed)
        self._log(f"Column ordering for {self.table}:", [self.domains[i].column.name for i in ordering])

        torch.manual_seed(params.seed)
        model = self._create_made(self.domains, params, ordering=ordering).to(self._device)
        self._log(f"Model for {self.table} has {model.n_parameters} parameters")

        data_bits = entropy_bits(joint_labels(*tokens.T))
        train_data = torch.as_tensor(tokens, dtype=torch.long)
        n_rows = len(train_data)
        batch_size = min(params.batch_size, n_rows)
        steps_per_epoch = math.ceil(n_rows / batch_size)
        n_epochs = max(params.epochs, math.ceil(params.min_training_steps / steps_per_epoch))

        optimizer = torch.optim.Adam(model.parameters(), lr=params.learning_rate)
        generator = torch.Generator().manual_seed(params.seed)
        epoch_bits: list[float] = []
        step = 0

        model.train()
        for epoch in range(n_epochs):
            permutation = torch.randperm(n_rows, generator=generator)
            total_loss = 0.0
            for batch_start in range(0, n_rows, batch_size):
                step += 1
                if params.warmup_steps > 0:
                    lr = params.learning_rate * min(1.0, step / params.warmup_steps)
                    for group in optimizer.param_groups:
                        group["lr"] = lr

                batch = train_data[permutation[batch_start : batch_start + batch_size]].to(self._device)
                loss = model.nll(model(batch), batch).mean()
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()
                total_loss += loss.item() * len(batch)

            bits = total_loss / n_rows / math.log(2)
            epoch_bits.append(bits)
            self._log(
                f"[{self.table}] epoch {epoch + 1}/{n_epochs}: {bits:.3f} bits/tuple "
                f"(entropy gap {bits - data_bits:.3f} bits, includes column masking)"
            )

        model.eval()
        model_bits = self._evaluate_bits(model, train_data)
        training_time = time.perf_counter() - start_time
        self._log(
            f"[{self.table}] training done after {training_time:.1f}s: model {model_bits:.3f} bits/tuple, "
            f"data {data_bits:.3f} bits/tuple, entropy gap {model_bits - data_bits:.3f} bits"
        )

        self.model = model
        self.training_metrics = {
            "status": "completed",
            "n_rows": n_rows,
            "n_columns": len(self.domains),
            "n_parameters": model.n_parameters,
            "model_size_mb": model.n_parameters * 4 / 1024**2,
            "epochs": n_epochs,
            "steps": step,
            "epoch_bits": epoch_bits,
            "data_bits": data_bits,
            "model_bits": model_bits,
            "entropy_gap_bits": model_bits - data_bits,
            "training_time_s": training_time,
        }
        return self.training_metrics

    def selectivity(self, filters: pb.qal.AbstractPredicate | None, *, ignore_unsupported: bool = False) -> float:
        """Estimates the fraction of rows of the table that satisfy a filter predicate.

        Parameters
        ----------
        filters : pb.qal.AbstractPredicate | None
            All filters on the table. *None* means that the table is not filtered at all.
        ignore_unsupported : bool, optional
            Whether to ignore conjuncts of the filter that cannot be evaluated (see `predicate_regions`). By
            default, an `UnsupportedPredicateError` is raised for such predicates.

        Raises
        ------
        UnsupportedPredicateError
            If (a part of) the predicate cannot be evaluated by Naru, e.g. because it references a column that is not
            modeled.
        """
        if filters is None:
            return 1.0

        terms = predicate_regions(
            filters,
            resolve=self._resolve,
            max_terms=self.hyper_params.max_inclusion_exclusion_terms,
            ignore_unsupported=ignore_unsupported,
        )
        selectivity = sum(coef * self.region_selectivity(region) for coef, region in terms)
        return min(max(selectivity, 0.0), 1.0)

    def estimate(self, filters: pb.qal.AbstractPredicate | None, *, ignore_unsupported: bool = False) -> pb.Cardinality:
        """Estimates the number of rows that satisfy a filter predicate. See `selectivity` for details."""
        return pb.Cardinality(self.selectivity(filters, ignore_unsupported=ignore_unsupported) * self.row_count)

    def region_selectivity(self, region: Region) -> float:
        """Estimates the probability mass of a conjunctive query region using progressive sampling."""
        weights: dict[int, torch.Tensor] = {}
        for col, values in region.constraints.items():
            col_weights = self.domains[col].token_weights(values)
            if np.all(col_weights >= 1.0):
                continue  # the constraint does not restrict the column at all
            weights[col] = torch.from_numpy(col_weights).to(self._device)

        if not weights:
            return 1.0
        if self.model is None:
            raise RuntimeError(f"Naru model for table {self.table} has not been trained yet")

        generator = torch.Generator(device=self._device).manual_seed(self.hyper_params.seed)
        return progressive_sampling(
            self.model,
            weights,
            n_samples=self.hyper_params.num_samples,
            generator=generator,
        )

    def store(self, directory: Path) -> dict[str, Any]:
        """Persists the column domains and model weights in a directory.

        Returns
        -------
        dict[str, Any]
            A JSON-serializable catalog entry that can be passed to `load` to re-create the model. All file paths in
            the entry are relative to `directory`.
        """
        table_name = _file_name(self.table.full_name)
        columns: list[dict[str, Any]] = []
        for domain in self.domains:
            domain_file = Path("domains") / table_name / f"{_file_name(domain.column.name)}.parquet"
            domain.store(directory / domain_file)
            columns.append(
                {
                    "column": domain.column,
                    "dtype": domain.dtype,
                    "null_count": domain.null_count,
                    "domain_file": str(domain_file),
                }
            )

        model_file: Path | None = None
        if self.model is not None:
            model_file = Path("models") / f"naru-{table_name}.pt"
            (directory / model_file).parent.mkdir(parents=True, exist_ok=True)
            torch.save(self.model.state_dict(), directory / model_file)

        return {
            "table": self.table,
            "row_count": self.row_count,
            "columns": columns,
            "ordering": self.ordering,
            "model_file": str(model_file) if model_file is not None else None,
            "training_metrics": self.training_metrics,
        }

    def describe(self) -> pb.util.jsondict:
        metrics = {k: v for k, v in self.training_metrics.items() if k != "epoch_bits"}
        return {
            "table": self.table,
            "columns": [domain.column.name for domain in self.domains],
            "ordering": [self.domains[i].column.name for i in self.ordering],
            "training": metrics,
        }

    def __repr__(self) -> str:
        return f"NaruTableModel({self.table}, columns={[d.column.name for d in self.domains]})"

    def _resolve(self, column: pb.ColumnReference) -> tuple[int, ColumnDomain]:
        idx = self._column_index.get(column.name.lower())
        if idx is None:
            raise UnsupportedPredicateError(f"Column {column} is not modeled by Naru (table {self.table})")
        return idx, self.domains[idx]

    @staticmethod
    def _create_made(domains: Sequence[ColumnDomain], params: NaruHyperParams, *, ordering: Sequence[int]) -> MADE:
        return MADE(
            [domain.n_tokens for domain in domains],
            hidden_sizes=params.hidden_sizes,
            ordering=ordering,
            input_encoding=params.input_encoding,
            output_encoding=params.output_encoding,
            embed_size=params.embed_size,
            residual=params.residual,
            direct_io=params.direct_io,
            column_masking=params.column_masking,
            seed=params.seed,
        )

    @torch.no_grad()
    def _evaluate_bits(self, model: MADE, data: torch.Tensor, batch_size: int = 8192) -> float:
        """Computes the average negative log-likelihood of the data in bits per tuple (without column masking)."""
        total = 0.0
        for start in range(0, len(data), batch_size):
            batch = data[start : start + batch_size].to(self._device)
            total += model.nll(model(batch), batch).sum().item()
        return total / len(data) / math.log(2)
