from __future__ import annotations

import math
import re
import time
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import numpy as np
import postbound as pb
import torch
from postbound.qal import FunctionExpression, Limit, OrderBy, Ordering, Projection, Select, as_query

from ..util import wrap_logger
from ._domain import ColumnDomain, UnsupportedPredicateError
