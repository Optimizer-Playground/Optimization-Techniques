from __future__ import annotations

from collections.abc import Mapping

import torch

from ._made import MADE


@torch.no_grad()
def progressive_sampling(
    model: MADE,
    weights: Mapping[int, torch.Tensor],
    *,
    n_samples: int,
    generator: torch.Generator | None = None,
) -> float:
    """Estimates the probability mass of a query region using progressive sampling (Algorithm 1 of the paper).

    The query region is given by per-column token weights. For the usual Naru setting, the weight of a token is 1 if
    the token is part of the column's valid region *R_i* and 0 otherwise. For bucketized domains, the weight is the
    fraction of the bucket that is part of the valid region (see `ColumnDomain.token_weights`). Columns without
    weights are wildcards.

    For each sample path, we walk the columns in the model's autoregressive order. For each constrained column, we
    compute the conditional distribution *P(X_i | x_<i)*, store the probability mass of the valid region, and sample
    the next value from the distribution restricted to the valid region. The density estimate is the product of all
    stored masses, averaged over all sample paths.

    If the model was trained with column masking, wildcard columns are skipped entirely (*wildcard-skipping*, Section
    5.2 of the paper): they keep their [MASK] representation and do not require a forward pass. Otherwise, wildcards
    are sampled from their unrestricted conditional distribution. In both cases, columns that come after the last
    constrained column in the ordering are never visited.

    Parameters
    ----------
    model : MADE
        The trained autoregressive model.
    weights : Mapping[int, torch.Tensor]
        Maps the (natural) column index to the weights of its tokens. Must be on the same device as the model.
    n_samples : int
        The number of sample paths.
    generator : torch.Generator | None, optional
        Source of randomness for the sampling process. Use a seeded generator to obtain deterministic estimates.

    Returns
    -------
    float
        The estimated selectivity of the region.
    """
    if not weights:
        return 1.0
    if any(not bool((w > 0).any()) for w in weights.values()):
        return 0.0

    device = next(model.parameters()).device
    last_position = max(int(model.position[col]) for col in weights)
    wildcard_skipping = model.column_masking

    inp = torch.zeros(n_samples, int(model.input_offsets[-1]), device=device)
    if wildcard_skipping:
        for col in range(model.nin):
            lo, hi = int(model.input_offsets[col]), int(model.input_offsets[col + 1])
            inp[:, lo:hi] = model.encode_column(None, col)

    density = torch.ones(n_samples, device=device)
    paths_diverged = False  # as long as no value was sampled, all sample paths share the same input

    for position in range(last_position + 1):
        col = model.ordering[position]
        col_weights = weights.get(col)
        if col_weights is None and wildcard_skipping:
            continue

        # Before the first value is sampled, all sample paths are identical and a single forward pass suffices.
        model_input = inp if paths_diverged else inp[:1]
        logits = model.forward_with_encoded_input(model_input)
        probs = torch.softmax(model.logits_for_col(col, logits), dim=1)

        if col_weights is not None:
            probs = probs * col_weights
            mass = probs.sum(dim=1)
            density = density * mass
            if position == last_position:
                break
            # Paths that left the high-density region have zero mass. Their sampled value is irrelevant, but
            # multinomial() requires at least one non-zero probability per row.
            probs = probs.masked_fill((mass <= 0).view(-1, 1), 1.0)

        if paths_diverged:
            samples = torch.multinomial(probs, num_samples=1, replacement=True, generator=generator).view(-1)
        else:
            samples = torch.multinomial(probs[0], num_samples=n_samples, replacement=True, generator=generator)

        lo, hi = int(model.input_offsets[col]), int(model.input_offsets[col + 1])
        inp[:, lo:hi] = model.encode_column(samples, col)
        paths_diverged = True

    return float(density.mean().item())
