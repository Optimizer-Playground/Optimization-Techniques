from __future__ import annotations

import itertools
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from typing import override

import postbound as pb

from ._domain import ColumnDomain, TruthMask, UnsupportedPredicateError, ValueSet


@dataclass(frozen=True)
class Region:
    """A conjunctive query region *R_1 x ... x R_n* over the columns of a table.

    Each constrained column is mapped to the set of its valid values. Columns that are not part of the mapping are
    wildcards. The empty region (i.e. a region without any constraints) corresponds to the entire table.
    """

    constraints: Mapping[int, ValueSet]

    @staticmethod
    def everything() -> Region:
        return Region({})

    def intersect(self, other: Region) -> Region | None:
        """Computes the intersection with another region. Returns *None* if the intersection is empty."""
        merged = dict(self.constraints)
        for col, values in other.constraints.items():
            merged[col] = merged[col].intersect(values) if col in merged else values
            if merged[col].is_empty():
                return None
        return Region(merged)

    def key(self) -> tuple:
        return tuple(sorted((col, values.key()) for col, values in self.constraints.items()))


SignedRegions = list[tuple[int, Region]]
"""A linear combination of regions. The selectivity of the combination is *sum(coef * P(region))*."""


class _Node:
    pass


@dataclass
class _Leaf(_Node):
    column: int
    truth: TruthMask


@dataclass
class _And(_Node):
    children: list[_Node]


@dataclass
class _Or(_Node):
    children: list[_Node]


@dataclass
class _Not(_Node):
    child: _Node


class _PredicateTreeBuilder(pb.qal.PredicateVisitor[_Node]):
    """Translates a PostBOUND predicate into an intermediate tree whose leaves are evaluated on the column domains."""

    def __init__(self, resolve: Callable[[pb.ColumnReference], tuple[int, ColumnDomain]]) -> None:
        self._resolve = resolve

    @override
    def visit_binary_predicate(self, predicate: pb.qal.BinaryPredicate, *args, **kwargs) -> _Node:
        return self._leaf(predicate)

    @override
    def visit_between_predicate(self, predicate: pb.qal.BetweenPredicate, *args, **kwargs) -> _Node:
        return self._leaf(predicate)

    @override
    def visit_in_predicate(self, predicate: pb.qal.InPredicate, *args, **kwargs) -> _Node:
        return self._leaf(predicate)

    @override
    def visit_unary_predicate(self, predicate: pb.qal.UnaryPredicate, *args, **kwargs) -> _Node:
        return self._leaf(predicate)

    @override
    def visit_not_predicate(self, predicate: pb.qal.NotPredicate, *args, **kwargs) -> _Node:
        return _Not(predicate.child.accept_visitor(self, *args, **kwargs))

    @override
    def visit_or_predicate(self, predicate: pb.qal.OrPredicate, *args, **kwargs) -> _Node:
        return _Or([child.accept_visitor(self, *args, **kwargs) for child in predicate.children])

    @override
    def visit_and_predicate(self, predicate: pb.qal.AndPredicate, *args, **kwargs) -> _Node:
        return _And([child.accept_visitor(self, *args, **kwargs) for child in predicate.children])

    def _leaf(self, predicate: pb.qal.AbstractPredicate) -> _Leaf:
        simplified = pb.qal.SimpleFilter.attempt_wrap(predicate)
        if simplified is None:
            raise UnsupportedPredicateError(f"Predicate {predicate} is not a simple filter")
        col_idx, domain = self._resolve(simplified.column)
        return _Leaf(col_idx, domain.evaluate(simplified))


def _simplify(node: _Node) -> _Node:
    """Merges all subtrees that only reference a single column into a single leaf.

    Predicates on the same column can be combined exactly by evaluating them on the column's domain. This also
    implements the paper's notion of a valid region per column (e.g. ``a >= 1 AND a <= 5`` becomes ``a IN [1, 5]``).
    """
    match node:
        case _Leaf():
            return node
        case _Not(child):
            child = _simplify(child)
            return _Leaf(child.column, child.truth.negate()) if isinstance(child, _Leaf) else _Not(child)
        case _And(children) | _Or(children):
            combine = TruthMask.conjunction if isinstance(node, _And) else TruthMask.disjunction
            leaves: dict[int, TruthMask] = {}
            others: list[_Node] = []
            for child in (_simplify(c) for c in children):
                if not isinstance(child, _Leaf):
                    others.append(child)
                elif child.column in leaves:
                    leaves[child.column] = combine(leaves[child.column], child.truth)
                else:
                    leaves[child.column] = child.truth
            merged: list[_Node] = [_Leaf(col, truth) for col, truth in leaves.items()]
            merged.extend(others)
            if len(merged) == 1:
                return merged[0]
            return _And(merged) if isinstance(node, _And) else _Or(merged)
        case _:
            raise TypeError(f"Unknown node type {node}")


class _TermExpansion:
    """Expands a predicate tree into a linear combination of conjunctive regions (inclusion-exclusion principle).

    For each node we compute the regions where the node evaluates to *true* and where it evaluates to *false*. Both are
    required to handle negations correctly under SQL's three-valued logic: *NOT p* is true exactly where *p* is false,
    which is not the same as *1 - P(p)* if NULL values are involved.
    """

    def __init__(self, max_terms: int) -> None:
        self._max_terms = max_terms

    def true_terms(self, node: _Node) -> SignedRegions:
        match node:
            case _Leaf(column, truth):
                return self._leaf_terms(column, truth.true)
            case _And(children):
                return self._product([self.true_terms(c) for c in children])
            case _Or(children):
                return self._union([self.true_terms(c) for c in children])
            case _Not(child):
                return self.false_terms(child)
            case _:
                raise TypeError(f"Unknown node type {node}")

    def false_terms(self, node: _Node) -> SignedRegions:
        match node:
            case _Leaf(column, truth):
                return self._leaf_terms(column, truth.false)
            case _And(children):
                return self._union([self.false_terms(c) for c in children])
            case _Or(children):
                return self._product([self.false_terms(c) for c in children])
            case _Not(child):
                return self.true_terms(child)
            case _:
                raise TypeError(f"Unknown node type {node}")

    def _leaf_terms(self, column: int, values: ValueSet) -> SignedRegions:
        if values.is_empty():
            return []
        if values.is_full():
            return [(1, Region.everything())]
        return [(1, Region({column: values}))]

    def _product(self, operands: Sequence[SignedRegions]) -> SignedRegions:
        """Conjunction: P(A and B) is the pairwise intersection of all terms."""
        result: SignedRegions = [(1, Region.everything())]
        for terms in operands:
            combined: SignedRegions = []
            for (coef_a, region_a), (coef_b, region_b) in itertools.product(result, terms):
                intersection = region_a.intersect(region_b)
                if intersection is not None:
                    combined.append((coef_a * coef_b, intersection))
            result = self._normalize(combined)
        return result

    def _union(self, operands: Sequence[SignedRegions]) -> SignedRegions:
        """Disjunction via inclusion-exclusion: P(A or B) = P(A) + P(B) - P(A and B)."""
        result: SignedRegions = []
        for terms in operands:
            overlap = self._product([result, terms])
            negated_overlap = [(-coef, region) for coef, region in overlap]
            result = self._normalize(result + terms + negated_overlap)
        return result

    def _normalize(self, terms: SignedRegions) -> SignedRegions:
        merged: dict[tuple, tuple[int, Region]] = {}
        for coef, region in terms:
            key = region.key()
            prev_coef = merged[key][0] if key in merged else 0
            merged[key] = (prev_coef + coef, region)
        normalized = [(coef, region) for coef, region in merged.values() if coef != 0]
        if len(normalized) > self._max_terms:
            raise UnsupportedPredicateError(
                f"Predicate requires more than {self._max_terms} inclusion-exclusion terms. "
                "Increase the limit if you really want to evaluate it."
            )
        return normalized


def predicate_regions(
    predicate: pb.qal.AbstractPredicate,
    *,
    resolve: Callable[[pb.ColumnReference], tuple[int, ColumnDomain]],
    max_terms: int = 64,
    ignore_unsupported: bool = False,
) -> SignedRegions:
    """Translates a filter predicate into a linear combination of conjunctive query regions.

    Naru's progressive sampling can only compute the probability mass of a conjunctive region *R_1 x ... x R_n*, i.e.
    of a conjunction of single-column predicates. To support arbitrary predicates, we proceed in two steps:

    1. All predicates that reference a single column are evaluated directly on the column's domain. This handles
       arbitrary nesting of *AND*, *OR*, and *NOT* on the same column, as well as all operators that can be evaluated
       on static values (e.g. ranges, *IN*, *LIKE*, *IS NULL*).
    2. Disjunctions and negations that span multiple columns are expanded using the inclusion-exclusion principle (as
       suggested in Section 2.2 of the paper). This results in a (signed) sum of conjunctive regions.

    For the common case of a conjunction of filters, the result is a single region.

    Parameters
    ----------
    predicate : pb.qal.AbstractPredicate
        The filter predicate. It may only reference columns of a single table.
    resolve : Callable[[pb.ColumnReference], tuple[int, ColumnDomain]]
        Maps a column to its index in the model and its domain. Should raise an `UnsupportedPredicateError` if the
        column is not modeled.
    max_terms : int, optional
        The maximum number of terms of the inclusion-exclusion expansion. Larger expansions raise an
        `UnsupportedPredicateError`.
    ignore_unsupported : bool, optional
        If enabled, top-level conjuncts that cannot be evaluated are dropped (i.e. treated as always true) instead of
        raising an error. This leads to an overestimation of the selectivity.

    Returns
    -------
    SignedRegions
        Pairs of (coefficient, region). The selectivity of the predicate is *sum(coef * P(region))*.

    Raises
    ------
    UnsupportedPredicateError
        If (a part of) the predicate cannot be evaluated by Naru.
    """
    conjuncts = predicate.children if isinstance(predicate, pb.qal.AndPredicate) else [predicate]
    builder = _PredicateTreeBuilder(resolve)
    nodes: list[_Node] = []
    for conjunct in conjuncts:
        try:
            nodes.append(conjunct.accept_visitor(builder))
        except UnsupportedPredicateError:
            if not ignore_unsupported:
                raise

    tree = _simplify(_And(nodes)) if nodes else None
    if tree is None:
        return [(1, Region.everything())]
    return _TermExpansion(max_terms).true_terms(tree)
