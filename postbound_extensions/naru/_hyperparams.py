from __future__ import annotations

from dataclasses import asdict, dataclass, field, replace
from typing import Any

import postbound as pb
import torch

from ._made import InputEncoding, OutputEncoding
from ._ordering import OrderingStrategy


@dataclass(frozen=True)
class NaruHyperParams:
    """Hyperparameters for the Naru models (architecture, training, and inference).

    Use `default` to obtain our recommended configuration and `replace` (or `dataclasses.replace`) to adjust
    individual parameters. All parameters apply to all per-table models of an estimator.

    Model architecture
    ------------------
    hidden_sizes : tuple[int, ...]
        Number of units of each hidden layer.
    residual : bool
        Use residual connections between hidden layers of equal size (ResMADE) instead of a plain MADE.
    direct_io : bool
        Add direct (masked) connections between input and output layer.
    input_encoding : InputEncoding
        How column values are encoded (*embed*, *one_hot*, or *binary*).
    output_encoding : OutputEncoding
        How output distributions are decoded (*embed* for embedding reuse, or *one_hot*).
    embed_size : int
        Embedding size *h*. Columns with at most *h* tokens are one-hot encoded instead.
    column_masking : bool
        Train with randomly masked columns, which enables wildcard-skipping during inference.
    ordering : OrderingStrategy
        Heuristic to determine the column ordering of the autoregressive factorization.

    Data
    ----
    max_domain_size : int | None
        Columns with more distinct values are bucketized into (roughly) this many equi-depth buckets. *None* always
        uses the exact dictionary encoding of the paper.
    max_training_rows : int | None
        Train on a uniform sample of at most this many rows per table. *None* uses the entire table.

    Training
    --------
    epochs : int
        Number of passes over the training data.
    min_training_steps : int
        Minimum number of gradient steps. For small tables, the number of epochs is increased accordingly.
    batch_size : int
        Number of tuples per gradient step.
    learning_rate : float
        (Peak) learning rate of the Adam optimizer.
    warmup_steps : int
        Number of steps for a linear learning rate warmup. 0 disables the warmup.

    Inference
    ---------
    num_samples : int
        Number of progressive sampling paths per estimate (*Naru-2000* in the paper).
    max_inclusion_exclusion_terms : int
        Upper limit for the expansion of disjunctive predicates that span multiple columns.

    Miscellaneous
    -------------
    seed : int
        Seed for weight initialization, training, and progressive sampling (estimates are deterministic).
    device : str | None
        The torch device to use for training and inference. *None* selects CUDA if available and the CPU otherwise.
        The device is not persisted along with the model.
    """

    hidden_sizes: tuple[int, ...] = (256, 256, 256, 256, 256)
    residual: bool = True
    direct_io: bool = True
    input_encoding: InputEncoding = "embed"
    output_encoding: OutputEncoding = "embed"
    embed_size: int = 64
    column_masking: bool = True
    ordering: OrderingStrategy = "natural"

    max_domain_size: int | None = 1024
    max_training_rows: int | None = None

    epochs: int = 20
    min_training_steps: int = 6000
    batch_size: int = 1024
    learning_rate: float = 5e-3
    warmup_steps: int = 200

    num_samples: int = 2000
    max_inclusion_exclusion_terms: int = 64

    seed: int = 42
    device: str | None = field(default=None, compare=False)

    @staticmethod
    def default() -> NaruHyperParams:
        """Our recommended configuration.

        The architecture follows the recommendation of the reference implementation's README: a ResMADE with 5 hidden
        layers of 256 units, direct input/output connections and column masking (i.e. wildcard-skipping). In contrast
        to the reference implementation (which defaults to a binary input encoding), we use the encoding strategy
        described in Section 4.2 of the paper: embeddings of size 64 for large domains, one-hot encodings for small
        domains, and embedding reuse for the output layer. Columns are factorized in their natural order (as in the
        paper's evaluation) and 2000 progressive samples are used per estimate (*Naru-2000*).

        The remaining parameters are not specified by the paper. We chose them based on the entropy gap of the
        trained models (i.e. without looking at any query): columns with more than 1024 distinct values are
        bucketized, models are trained for 20 epochs (but at least 6000 gradient steps, which matters for small
        tables) with a batch size of 1024 and Adam with a learning rate of 0.005 after a warmup of 200 steps.
        """
        return NaruHyperParams()

    @staticmethod
    def from_json(json_data: dict[str, Any]) -> NaruHyperParams:
        params = dict(json_data)
        if "hidden_sizes" in params:
            params["hidden_sizes"] = tuple(params["hidden_sizes"])
        return NaruHyperParams(**params)

    def replace(self, **changes: Any) -> NaruHyperParams:
        """Creates a copy of the hyperparameters with some values changed."""
        return replace(self, **changes)

    def resolve_device(self) -> torch.device:
        if self.device is not None:
            return torch.device(self.device)
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")

    def __json__(self) -> pb.util.jsondict:
        params = asdict(self)
        params["hidden_sizes"] = list(self.hidden_sizes)
        params.pop("device")  # the device is a property of the runtime environment, not of the model
        return params
