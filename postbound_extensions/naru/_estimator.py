UnsupportedPolicy = Literal["unknown", "ignore"]
"""How the estimator handles filters that Naru cannot evaluate.

- *unknown*: return an unknown cardinality for the entire table (default)
- *ignore*: drop the unsupported conjuncts and estimate the remaining filters (overestimates the cardinality)
"""


def _table_key(table: pb.TableReference) -> str:
    return table.full_name.lower()


@dataclass
class ModelSpec:
    """Describes which tables and columns should be modeled by Naru.

    Naru builds one autoregressive model per table. Each model captures the joint distribution of the specified
    columns. Columns are factorized in the order in which they appear in the spec (for the *natural* ordering), which
    corresponds to the order of the columns in the database schema if the spec was inferred automatically.

    Use `from_schema` to model (almost) all columns of all tables, or `from_workload` to only model the tables and
    columns that are filtered in a specific workload.

    Attributes
    ----------
    tables : dict[pb.TableReference, list[pb.ColumnReference]]
        Maps each table to the columns that should be modeled. Tables without columns are supported: they only
        provide the (unfiltered) table cardinality.
    """

    tables: dict[pb.TableReference, list[pb.ColumnReference]] = field(default_factory=dict)

    @staticmethod
    def from_schema(
        database: pb.Database,
        *,
        tables: Iterable[pb.TableReference] | None = None,
        max_text_domain: int | None = None,
        verbose: bool | pb.util.Logger = False,
    ) -> ModelSpec:
        """Models all columns of all tables in the database schema.

        This is the setting described in the paper: Naru approximates the full joint distribution of each table
        and does not need to know anything about the workload.

        Parameters
        ----------
        database : pb.Database
            The database whose schema should be modeled.
        tables : Iterable[pb.TableReference] | None, optional
            Restricts the spec to specific tables. By default, all tables are modeled (except for Postgres system
            tables).
        max_text_domain : int | None, optional
            Text columns with more distinct values than this threshold are considered "free text" (e.g. comments or
            descriptions) and are not modeled. Their dictionary would essentially be a copy of the column. *None*
            includes all text columns.
        verbose : bool | pb.util.Logger, optional
            Whether to log which columns are skipped.

        Notes
        -----
        Columns with data types that Naru cannot model (e.g. arrays or JSON) are skipped.
        """
        log = wrap_logger(verbose)
        schema = database.schema()
        stats = pb.db.PreciseStatistics(database)

        if tables is None:
            candidate_tables = [tab for tab in schema.tables() if not tab.full_name.startswith("pg_")]
        else:
            candidate_tables = [_resolve_table(tab, schema) for tab in tables]

        spec = ModelSpec()
        for table in candidate_tables:
            columns: list[pb.ColumnReference] = []
            for col in schema.columns(table):
                dtype = schema.datatype(col)
                kind = column_kind(dtype)
                if kind is None:
                    log("Skipping column", col, f"- unsupported data type '{dtype}'")
                    continue
                if kind == ColumnKind.Text and max_text_domain is not None:
                    n_distinct = stats.num_distinct(col)
                    if n_distinct > max_text_domain:
                        log("Skipping column", col, f"- free text with {n_distinct} distinct values")
                        continue
                columns.append(col)
            spec.tables[table] = columns

        return spec

    @staticmethod
    def from_workload(
        workload: pb.Workload | Iterable[pb.SqlQuery],
        *,
        database: pb.Database,
        verbose: bool | pb.util.Logger = False,
    ) -> ModelSpec:
        """Only models the tables and columns that are filtered in a specific workload.

        In contrast to `from_schema`, this produces much smaller models that are tailored to the workload. All
        tables of the workload are included. For each table, we model exactly those columns that appear in at least
        one filter predicate (regardless of the predicate type).

        Parameters
        ----------
        workload : pb.Workload | Iterable[pb.SqlQuery]
            The queries to analyze.
        database : pb.Database
            The database that contains the tables. Used to resolve the columns of the queries to their schema
            counterparts.
        verbose : bool | pb.util.Logger, optional
            Whether to log columns that cannot be modeled.
        """
        log = wrap_logger(verbose)
        schema = database.schema()
        queries = workload.queries() if isinstance(workload, pb.Workload) else workload

        filter_columns: dict[pb.TableReference, set[pb.ColumnReference]] = {}
        for query in queries:
            for table in query.tables():
                if table.virtual:
                    continue
                filter_columns.setdefault(_resolve_table(table, schema), set())

            for predicate in query.filters():
                for col in predicate.columns():
                    if col.table is None or col.table.virtual:
                        continue
                    table = _resolve_table(col.table, schema)
                    schema_col = _resolve_column(col, table, schema)
                    if column_kind(schema.datatype(schema_col)) is None:
                        log("Skipping column", schema_col, f"- unsupported data type '{schema.datatype(schema_col)}'")
                        continue
                    filter_columns.setdefault(table, set()).add(schema_col)

        spec = ModelSpec()
        for table, columns in filter_columns.items():
            # keep the schema order of the columns to obtain a meaningful natural ordering
            spec.tables[table] = [col for col in schema.columns(table) if col in columns]
        return spec

    @staticmethod
    def from_json(json_data: dict[str, Any]) -> ModelSpec:
        spec = ModelSpec()
        for entry in json_data["tables"]:
            table = pb.parser.load_table_json(entry["table"])
            assert table is not None
            columns = [pb.parser.load_column_json(col) for col in entry["columns"]]
            spec.tables[table] = [col for col in columns if col is not None]
        return spec

    def __json__(self) -> pb.util.jsondict:
        return {"tables": [{"table": table, "columns": columns} for table, columns in self.tables.items()]}


def _resolve_table(table: pb.TableReference, schema: pb.db.DatabaseSchema) -> pb.TableReference:
    """Finds the table of the schema that corresponds to a (potentially aliased or differently cased) reference."""
    target = _table_key(table)
    for candidate in schema.tables():
        if _table_key(candidate) == target:
            return candidate
    raise KeyError(f"Table {table} does not exist in the database schema")


def _resolve_column(
    column: pb.ColumnReference, table: pb.TableReference, schema: pb.db.DatabaseSchema
) -> pb.ColumnReference:
    target = column.name.lower()
    for candidate in schema.columns(table):
        if candidate.name.lower() == target:
            return candidate
    raise KeyError(f"Column {column} does not exist in table {table}")


class NaruEstimator(pb.CardinalityEstimator):
    """Naru is an unsupervised, data-driven cardinality estimator based on deep autoregressive models.

    For each table, Naru learns the joint distribution of its columns with a neural network (`MADE`). Selectivities
    of filter predicates are computed by integrating over the learned distribution using progressive sampling. Naru
    is trained directly on the table data, no training queries are required.

    Like the original paper and reference implementation, our Naru only estimates **base tables**. For all
    intermediates that contain joins, the estimator returns an unknown cardinality. PostBOUND then falls back to the
    native estimates of the target database.

    Creating an estimator
    ---------------------
    The tables and columns that should be modeled are described by a `ModelSpec`. Depending on the use case, the
    estimator can be created using the following strategies:

    - `online` models (almost) all columns of all tables, which is the most realistic setting
    - `infer_from` only models the tables and columns that are filtered in a specific workload
    - `from_spec` uses an arbitrary spec
    - `pre_trained` loads an estimator that was persisted using `store`

    All of these strategies directly train the models. As a convenience, `load_or_build` loads a pre-trained estimator
    if it exists and creates (and stores) a new one otherwise.

    Alternatively, the estimator can also be integrated into PostBOUND's training protocol: an estimator created via
    the constructor without any models is trained when `fit_database` is called.

    Parameters
    ----------
    models : Mapping[pb.TableReference, NaruTableModel] | None, optional
        Pre-built per-table models. If omitted, the models are built by `fit_database`.
    spec : ModelSpec | None, optional
        The spec that `fit_database` uses to build the models. Defaults to `ModelSpec.from_schema`.
    hyper_params : NaruHyperParams, optional
        Hyperparameters that `fit_database` uses to build the models.
    unsupported : UnsupportedPolicy, optional
        How filters that Naru cannot evaluate are handled. By default, an unknown cardinality is returned.
    verbose : bool | pb.util.Logger, optional
        Whether to log progress information.

    See Also
    --------
    NaruTableModel : The model of a single table
    ModelSpec : Describes which tables and columns are modeled
    NaruHyperParams : Hyperparameters of the models

    References
    ----------
    .. Zongheng Yang et al.: "Deep Unsupervised Cardinality Estimation" (PVLDB 13(3), 2019)
       https://doi.org/10.14778/3368289.3368294
    """

    @staticmethod
    def online(
        database: pb.Database,
        *,
        hyper_params: NaruHyperParams = NaruHyperParams.default(),
        tables: Iterable[pb.TableReference] | None = None,
        verbose: bool | pb.util.Logger = False,
    ) -> NaruEstimator:
        """Builds an estimator that models (almost) all columns of all tables of the database.

        Free text columns (text columns with more than `max_domain_size` distinct values) are not modeled. See
        `ModelSpec.from_schema` for details.
        """
        spec = ModelSpec.from_schema(
            database, tables=tables, max_text_domain=hyper_params.max_domain_size, verbose=verbose
        )
        return NaruEstimator.from_spec(spec, database=database, hyper_params=hyper_params, verbose=verbose)

    @staticmethod
    def infer_from(
        workload: pb.Workload | Iterable[pb.SqlQuery],
        *,
        database: pb.Database,
        hyper_params: NaruHyperParams = NaruHyperParams.default(),
        verbose: bool | pb.util.Logger = False,
    ) -> NaruEstimator:
        """Builds an estimator that only models the tables and filter columns of a specific workload.

        See `ModelSpec.from_workload` for details.
        """
        spec = ModelSpec.from_workload(workload, database=database, verbose=verbose)
        return NaruEstimator.from_spec(spec, database=database, hyper_params=hyper_params, verbose=verbose)

    @staticmethod
    def from_spec(
        spec: ModelSpec,
        *,
        database: pb.Database,
        hyper_params: NaruHyperParams = NaruHyperParams.default(),
        verbose: bool | pb.util.Logger = False,
    ) -> NaruEstimator:
        """Builds and trains an estimator for an arbitrary spec."""
        estimator = NaruEstimator(spec=spec, hyper_params=hyper_params, verbose=verbose)
        estimator.fit_database(database)
        return estimator

    @staticmethod
    def pre_trained(
        catalog_path: Path | str,
        *,
        hyper_params: NaruHyperParams | None = None,
        device: str | None = None,
        unsupported: UnsupportedPolicy = "unknown",
        verbose: bool | pb.util.Logger = False,
    ) -> NaruEstimator:
        """Loads an estimator that was persisted using `store`.

        Parameters
        ----------
        catalog_path : Path | str
            The catalog file, or the directory that contains a *naru-catalog.json*.
        hyper_params : NaruHyperParams | None, optional
            Allows to overwrite the inference-related hyperparameters (e.g. `num_samples`). The architecture-related
            parameters must match the stored models. By default, the stored hyperparameters are used.
        device : str | None, optional
            The torch device to use for inference. Overwrites the device of `hyper_params`. By default, CUDA is used
            if available and the CPU otherwise.
        unsupported : UnsupportedPolicy, optional
            How filters that Naru cannot evaluate are handled.
        verbose : bool | pb.util.Logger, optional
            Whether to log progress information.

        See Also
        --------
        store : The inverse operation
        """
        log = wrap_logger(verbose)
        catalog_file = _catalog_file(Path(catalog_path))
        log("Loading pre-trained Naru estimator from", catalog_file)
        with open(catalog_file, "r") as f:
            catalog = json.load(f)

        directory = catalog_file.parent
        hyper_params = hyper_params or NaruHyperParams.from_json(catalog["hyper_parameters"])
        if device is not None:
            hyper_params = hyper_params.replace(device=device)
        spec = ModelSpec.from_json(catalog["spec"])
        models = {}
        for entry in catalog["tables"]:
            model = NaruTableModel.load(entry, directory=directory, hyper_params=hyper_params, verbose=verbose)
            models[model.table] = model

        estimator = NaruEstimator(
            models, spec=spec, hyper_params=hyper_params, unsupported=unsupported, verbose=verbose
        )
        estimator._training_time = catalog.get("training_time_s")
        return estimator

    @staticmethod
    def load_or_build(
        catalog_path: Path | str,
        *,
        database: pb.Database,
        workload: pb.Workload | None = None,
        hyper_params: NaruHyperParams = NaruHyperParams.default(),
        verbose: bool | pb.util.Logger = False,
    ) -> NaruEstimator:
        """Integrated training and storage procedure.

        If an estimator has already been stored at `catalog_path`, it is simply loaded. Otherwise, a new estimator is
        built and stored at that location. If a `workload` is given, the estimator is tailored to it (see
        `infer_from`). Otherwise, the entire schema is modeled (see `online`).
        """
        log = wrap_logger(verbose)
        catalog_path = Path(catalog_path)
        try:
            catalog_file = _catalog_file(catalog_path)
        except FileNotFoundError:
            catalog_file = None

        if catalog_file is not None:
            log("Catalog exists, loading pre-trained Naru estimator")
            return NaruEstimator.pre_trained(catalog_file, device=hyper_params.device, verbose=verbose)

        log("Catalog not found, building new Naru estimator")
        if workload is None:
            estimator = NaruEstimator.online(database, hyper_params=hyper_params, verbose=verbose)
        else:
            estimator = NaruEstimator.infer_from(
                workload, database=database, hyper_params=hyper_params, verbose=verbose
            )
        estimator.store(catalog_path)
        return estimator

    def __init__(
        self,
        models: Mapping[pb.TableReference, NaruTableModel] | None = None,
        *,
        spec: ModelSpec | None = None,
        hyper_params: NaruHyperParams = NaruHyperParams.default(),
        unsupported: UnsupportedPolicy = "unknown",
        verbose: bool | pb.util.Logger = False,
    ) -> None:
        super().__init__()
        self._log = wrap_logger(verbose)
        self._verbose = verbose
        self._spec = spec
        self.hyper_params = hyper_params
        self.unsupported: UnsupportedPolicy = unsupported
        self._models: dict[str, NaruTableModel] = {}
        self._training_time: float | None = None
        for model in (models or {}).values():
            self._models[_table_key(model.table)] = model

    @property
    def models(self) -> Mapping[str, NaruTableModel]:
        """The per-table models, keyed by the (lower-case) table name."""
        return self._models

    @property
    def spec(self) -> ModelSpec | None:
        return self._spec

    def model_for(self, table: pb.TableReference) -> NaruTableModel | None:
        """Provides the model of a specific table (ignoring its alias), or *None* if the table is not modeled."""
        return self._models.get(_table_key(table))

    @override
    def calculate_estimate(
        self,
        query: pb.SqlQuery,
        intermediate: pb.TableReference | Iterable[pb.TableReference],
    ) -> pb.Cardinality:
        tables = [intermediate] if isinstance(intermediate, pb.TableReference) else list(intermediate)
        if len(tables) != 1:
            # Naru only estimates base tables, joins are left to the target database
            return pb.Cardinality.unknown()

        table = tables[0]
        model = self.model_for(table)
        if model is None:
            return pb.Cardinality.unknown()

        filters = query.filters_for(table)
        try:
            return model.estimate(filters, ignore_unsupported=self.unsupported == "ignore")
        except UnsupportedPredicateError as e:
            self._log(f"Cannot estimate {table} in query {query}: {e}")
            return pb.Cardinality.unknown()

    @override
    def fit_database(self, database: pb.Database) -> pb.train.TrainingMetrics:
        """Builds and trains the per-table models according to the spec (or the database schema if no spec is given)."""
        start = time.perf_counter()
        if self._spec is None:
            self._spec = ModelSpec.from_schema(
                database, max_text_domain=self.hyper_params.max_domain_size, verbose=self._verbose
            )

        for table, columns in self._spec.tables.items():
            model = NaruTableModel.build(
                table, columns, database=database, hyper_params=self.hyper_params, verbose=self._verbose
            )
            self._models[_table_key(model.table)] = model

        self._training_time = time.perf_counter() - start
        return self.training_metrics

    @override
    def database_fit_completed(self) -> bool:
        return bool(self._models) and all(model.is_trained() for model in self._models.values())

    @property
    def training_metrics(self) -> pb.train.TrainingMetrics:
        """Training metrics of all per-table models."""
        return {
            "status": "completed" if self.database_fit_completed() else "untrained",
            "training_time_s": self._training_time,
            "tables": {name: model.training_metrics for name, model in self._models.items()},
        }

    def store(self, catalog_path: Path | str) -> Path:
        """Persists all models along with their column domains.

        Parameters
        ----------
        catalog_path : Path | str
            Either a JSON file for the catalog, or a directory. In the latter case, the catalog is stored as
            *naru-catalog.json* in that directory. Domains and model weights are stored in subdirectories next to the
            catalog file.

        Returns
        -------
        Path
            The path to the catalog file.

        See Also
        --------
        pre_trained : The inverse operation
        """
        catalog_path = Path(catalog_path)
        catalog_file = catalog_path if catalog_path.suffix == ".json" else catalog_path / "naru-catalog.json"
        directory = catalog_file.parent
        directory.mkdir(parents=True, exist_ok=True)

        self._log("Storing Naru estimator at", catalog_file)
        catalog = {
            "hyper_parameters": self.hyper_params,
            "spec": self._spec or ModelSpec({model.table: model.columns for model in self._models.values()}),
            "training_time_s": self._training_time,
            "tables": [model.store(directory) for model in self._models.values()],
        }
        with open(catalog_file, "w") as f:
            pb.util.to_json_dump(catalog, f)
        return catalog_file

    @override
    def describe(self) -> pb.util.jsondict:
        return {
            "name": "Naru",
            "hyper_parameters": self.hyper_params,
            "unsupported_predicates": self.unsupported,
            "tables": [model.describe() for model in self._models.values()],
        }


def _catalog_file(catalog_path: Path) -> Path:
    if catalog_path.is_dir():
        catalog_path = catalog_path / "naru-catalog.json"
    if not catalog_path.is_file():
        raise FileNotFoundError(f"Naru catalog {catalog_path} does not exist")
    return catalog_path
