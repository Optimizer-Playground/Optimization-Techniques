from __future__ import annotations

from typing import Literal

import numpy as np

OrderingStrategy = Literal["natural", "mutinfo", "pmutinfo", "random"]
"""Heuristics to determine the column ordering of the autoregressive model (Section 5.3 of the paper).

- *natural*: the left-to-right order of the table schema (paper default)
- *mutinfo*: start with the column of maximum entropy, then successively add the column that maximizes the mutual
  information with all columns chosen so far
- *pmutinfo*: like *mutinfo*, but maximize the pairwise mutual information with the last chosen column
- *random*: a random permutation of the columns
"""


def entropy_bits(labels: np.ndarray) -> float:
    """Computes the empirical entropy (in bits) of a sequence of discrete labels."""
    if not len(labels):
        return 0.0
    _, counts = np.unique(labels, return_counts=True)
    probs = counts / counts.sum()
    return float(-(probs * np.log2(probs)).sum())


def joint_labels(*columns: np.ndarray) -> np.ndarray:
    """Maps each row of multiple discrete columns to a single label that identifies the combination of values."""
    if not columns:
        raise ValueError("At least one column is required")
    stacked = np.stack([np.asarray(c, dtype=np.int64) for c in columns], axis=1)
    _, labels = np.unique(stacked, axis=0, return_inverse=True)
    return labels.reshape(-1)


def compute_ordering(
    strategy: OrderingStrategy,
    tokens: np.ndarray,
    *,
    seed: int = 0,
    max_rows: int = 100_000,
) -> list[int]:
    """Determines the order of the columns in the autoregressive factorization.

    Parameters
    ----------
    strategy : OrderingStrategy
        The ordering heuristic to use.
    tokens : np.ndarray
        The dictionary-encoded table data of shape [n_rows, n_cols]. Only used for the information-theoretic orderings.
    seed : int, optional
        Seed for the random ordering and for sub-sampling large tables.
    max_rows : int, optional
        The information-theoretic orderings are computed on a uniform sample of at most this many rows.

    Returns
    -------
    list[int]
        The column indices in the order in which they should be factorized.
    """
    n_cols = tokens.shape[1]
    rng = np.random.default_rng(seed)
    match strategy:
        case "natural":
            return list(range(n_cols))
        case "random":
            return [int(i) for i in rng.permutation(n_cols)]
        case "mutinfo" | "pmutinfo":
            pass
        case _:
            raise ValueError(f"Unknown ordering strategy '{strategy}'")

    if n_cols <= 1:
        return list(range(n_cols))
    if tokens.shape[0] > max_rows:
        tokens = tokens[rng.choice(tokens.shape[0], size=max_rows, replace=False)]

    marginal_entropies = [entropy_bits(tokens[:, i]) for i in range(n_cols)]
    first = int(np.argmax(marginal_entropies))
    ordering = [first]
    context = tokens[:, first]
    context_entropy = marginal_entropies[first]

    while len(ordering) < n_cols:
        best_col, best_info, best_labels, best_entropy = -1, -np.inf, context, context_entropy
        for col in range(n_cols):
            if col in ordering:
                continue
            labels = joint_labels(context, tokens[:, col])
            joint_entropy = entropy_bits(labels)
            mutual_info = context_entropy + marginal_entropies[col] - joint_entropy
            if mutual_info > best_info + 1e-12:
                best_col, best_info, best_labels, best_entropy = col, mutual_info, labels, joint_entropy

        ordering.append(best_col)
        if strategy == "mutinfo":
            context, context_entropy = best_labels, best_entropy
        else:
            context, context_entropy = tokens[:, best_col], marginal_entropies[best_col]

    return ordering
