IncidenceGraph = nx.Graph


def lp_join_graph(query: pb.SqlQuery) -> IncidenceGraph:
    """Deconstructs a query into an LpBound-specific join graph.

    The join graph bipartite: all relations are on one side (annotated by ``bipartite="relation"``). On the other side
    are the join key equivalence classes (annotated by ``bipartite="variable"``). An edge connects a relation *R* with a
    join variable *X* if *R* contains a join column that is part of the equivalence class represented by *X*.
    """
    if not pb.qal.is_select_query(query):
        raise pb.qal.QueryTypeError.expected_select(query)

    joins = query.joins()
    if not pb.qal.all_binary_predicates(joins):
        raise ValueError("All joins must be binary predicates for the LP join graph to be constructed.")

    equivalence_classes = pb.qal.determine_join_equivalence_classes(joins)
    incidence_graph = nx.Graph()

    for join in joins:
        join_cols = join.columns()
        relations = {col.table for col in join_cols}
        join_vars = [eqc for eqc in equivalence_classes if join_cols <= eqc]

        for rel in relations:
            incidence_graph.add_node(rel, bipartite="relation")
        for var in join_vars:
            incidence_graph.add_node(var, bipartite="variable")

        for rel, var in itertools.product(relations, join_vars):
            incidence_graph.add_edge(rel, var)

    return incidence_graph


def is_berge_acyclic(incidence_graph: IncidenceGraph) -> bool:
    """Checks, if a LpBound join graph is Berge-acyclic.

    A query is Berge-acyclic, if any two relation nodes are connected by at most one join variable node
    (i.e. join equivalence class).
    """
    return nx.is_forest(incidence_graph)


def _sort_key(node: object) -> str:
    """Deterministic ordering for graph nodes (frozensets of columns have no stable iteration order)."""
    if isinstance(node, frozenset):
        return ",".join(sorted(str(col) for col in node))
    return str(node)


class LpBerge:
    """The LPBerge linear program of LpBound (Sec. 4.1 of the paper) for Berge-acyclic queries.

    The LP has three kinds of real-valued variables, all of which are entropies (in bits):

    - ``h(X)`` for each join variable *X*, i.e. each join equivalence class
    - ``h(P_R)`` for each relation *R*, where *P_R* consolidates all attributes of *R* that do not participate in any
      join (the "private" variable, called ``0<alias>`` in the reference implementation)
    - ``h(V_R)`` for each relation *R*, where *V_R* is the set of all variables of *R* (its join variables plus *P_R*)

    The objective is to maximize ``E_Q = sum_R h(V_R) - sum_X (a_X - 1) h(X)`` with *a_X* being the number of relations
    that contain *X*. The optimum *E** yields the bound ``|Q| <= 2^E*``.

    Usage: create the LP from the incidence graph, add the statistics and additivity constraints, finalize and compute
    the bound. If any relation is known to be empty (i.e., all of its norms are zero), the bound is 0 without solving
    the LP.

    Notes
    -----
    Implementation generated by Claude Opus 5.5 (Anthropic), instructed and supervised by Rico Bergmann.
    """

    def __init__(self, incidence_graph: IncidenceGraph) -> None:
        if not is_berge_acyclic(incidence_graph):
            raise ValueError("LPBerge is only sound for Berge-acyclic queries")

        self._graph = incidence_graph
        self._relations = sorted(
            (node for node, kind in incidence_graph.nodes(data="bipartite") if kind == "relation"), key=_sort_key
        )
        self._join_vars = sorted(
            (node for node, kind in incidence_graph.nodes(data="bipartite") if kind == "variable"), key=_sort_key
        )
        self._col_to_var: dict[pb.ColumnReference, frozenset] = {col: var for var in self._join_vars for col in var}

        # Map every LP variable to its column index in the constraint matrix
        self._var_idx: dict[tuple[str, object], int] = {}
        for var in self._join_vars:
            self._var_idx[("join", var)] = len(self._var_idx)
        for rel in self._relations:
            self._var_idx[("private", rel)] = len(self._var_idx)
            self._var_idx[("atom", rel)] = len(self._var_idx)

        self._rows: list[np.ndarray] = []  # each row r encodes the constraint r @ h <= rhs
        self._rhs: list[float] = []
        self._empty_result = False

        self._objective: np.ndarray | None = None
        self._A_ub: np.ndarray | None = None
        self._b_ub: np.ndarray | None = None

    def add_statistics_constraints(self, statistics: Mapping[pb.ColumnReference, LpNorms]) -> Self:
        """Adds the constraints of Eq. (18) for the full and simple degree sequences ``deg_R(*|X)``.

        For each join column *R.x* with join variable *X* and each norm *p*, this adds

        - ``p * h(V_R) - (p-1) * h(X) <= p * log2(||deg_R(*|X)||_p)`` for finite *p* (with *p = 1* this is simply the
          cardinality constraint ``h(V_R) <= log2 |R|``)
        - ``h(V_R) - h(X) <= log2(||deg_R(*|X)||_inf)`` for the max-degree

        The l0 norm (number of distinct values) is not a constraint in LPBerge and thus ignored.
        Statistics on columns that are not part of the join graph are ignored as well.
        """
        for col, norms in statistics.items():
            join_var = self._col_to_var.get(col)
            if join_var is None:
                continue

            if norms.is_zero():
                # The (filtered) relation is empty, hence the entire join result is empty. log2(0) is undefined, so we
                # must not add the constraint to the LP but rather short-circuit the bound computation.
                self._empty_result = True
                continue

            atom_idx = self._var_idx[("atom", col.table)]
            join_idx = self._var_idx[("join", join_var)]

            for p, norm in norms.norms.items():
                if norm <= 0:
                    self._empty_result = True
                    continue
                if p < 1:
                    raise ValueError(f"Norm l{p} is not supported by LPBerge (only p >= 1 or p = inf)")

                row = np.zeros(len(self._var_idx))
                if np.isinf(p):
                    row[atom_idx] = 1
                    row[join_idx] = -1
                    rhs = np.log2(norm)
                else:
                    row[atom_idx] = p
                    row[join_idx] = -(p - 1)
                    rhs = p * np.log2(norm)

                self._rows.append(row)
                self._rhs.append(rhs)

        return self

    def add_additivity_constraints(self) -> Self:
        """Adds the 1 + |V_R| additivity constraints for each relation R.

        These are ``h(V_R) <= sum_{X in V_R} h(X)`` (sub-additivity), as well as ``h(X) <= h(V_R)`` for each variable
        *X* of *R* (monotonicity). *V_R* always includes the private variable *P_R*.
        """
        for rel in self._relations:
            atom_idx = self._var_idx[("atom", rel)]
            member_indices = [self._var_idx[("private", rel)]]
            member_indices += [self._var_idx[("join", var)] for var in self._graph.neighbors(rel)]

            # sub-additivity: h(V_R) - sum_X h(X) <= 0
            row = np.zeros(len(self._var_idx))
            row[atom_idx] = 1
            row[member_indices] = -1
            self._rows.append(row)
            self._rhs.append(0.0)

            # monotonicity: h(X) - h(V_R) <= 0
            for member_idx in member_indices:
                row = np.zeros(len(self._var_idx))
                row[member_idx] = 1
                row[atom_idx] = -1
                self._rows.append(row)
                self._rhs.append(0.0)

        return self

    def finalize(self) -> Self:
        """Assembles the objective and constraint matrix. No more constraints can be added afterwards."""
        # linprog minimizes, so we use the negated objective -E_Q = -sum_R h(V_R) + sum_X (a_X - 1) h(X)
        objective = np.zeros(len(self._var_idx))
        for rel in self._relations:
            objective[self._var_idx[("atom", rel)]] = -1
        for var in self._join_vars:
            n_atoms = self._graph.degree(var)
            objective[self._var_idx[("join", var)]] = n_atoms - 1
        # private variables have coefficient 0, they only appear in the constraints

        self._objective = objective
        self._A_ub = np.vstack(self._rows) if self._rows else np.zeros((0, len(self._var_idx)))
        self._b_ub = np.array(self._rhs)
        return self

    def compute_bound(self) -> pb.Cardinality:
        """Solves the LP and computes the bound ``2^E*``.

        Raises
        ------
        RuntimeError
            If the LP could not be solved. Typically, this happens if the LP is unbounded because some relation does
            not have any statistics constraints.
        """
        if self._empty_result:
            return pb.Cardinality.zero()
        if self._objective is None:
            raise RuntimeError("LpBerge must be finalized before computing the bound")

        # all variables are entropies, hence non-negative. This is also the default bound of linprog, but we make
        # it explicit for clarity.
        res = scipy.optimize.linprog(
            self._objective, A_ub=self._A_ub, b_ub=self._b_ub, bounds=(0, None), method="highs"
        )
        if res.status != 0:
            raise RuntimeError(f"Could not solve LPBerge: {res.message}")

        log_bound = -res.fun
        return pb.Cardinality(float(np.exp2(log_bound)))


_FlowNode = frozenset  # a node in the flow network: a set of LP variables, the empty set is the source
_FlowEdge = tuple[_FlowNode, _FlowNode]


@dataclass(frozen=True)
class _DegreeConstraint:
    """A simple degree constraint ``log2 ||deg(Y|X)||_p <= b`` with ``|X| <= 1`` and ``X ⊆ Y``."""

    cond: _FlowNode  # X
    target: _FlowNode  # Y
    p: float
    log_bound: float  # b


class LpFlow:
    """The LPflow linear program of LpBound (Sec. 4.2 of the paper) for arbitrary (incl. cyclic) queries.

    LPflow solves the *dual* of the entropy LP: instead of maximizing the entropy of the query result, it searches for
    the cheapest weights *w_i >= 0* of the degree constraints ``log2 ||deg(Y_i|X_i)||_p <= b_i`` such that the
    inequality ``h(all variables) <= sum_i w_i * (1/p h(X_i) + h(Y_i|X_i))`` is a valid Shannon inequality. The bound is
    ``|Q| <= 2^(sum_i w_i * b_i)``.

    Validity of the inequality is checked using a flow network. Its nodes are sets of LP variables: the source ∅, each
    single variable {X}, and the sets X_i and Y_i of the degree constraints. Each degree constraint contributes

    - a forward edge X_i -> Y_i with capacity *w_i* (the term ``w_i h(Y_i|X_i)``)
    - a forward edge ∅ -> X_i with capacity *w_i / p* if *p* is finite (the term ``w_i/p h(X_i)``)
    - backward edges Y_i -> ∅ and Y_i -> {y} for each y in Y_i with infinite capacity (monotonicity)

    The inequality is valid iff each variable {X} independently receives a flow of at least 1 from the source. Hence,
    the LP contains a separate flow for each variable, all of which share the edge capacities. A forward edge
    X -> Y can also be traversed backwards with infinite capacity (monotonicity ``h(X) <= h(Y)``), which is encoded by
    allowing negative flows on forward edges.

    The LP variables are the same as for `LpBerge`: one per join variable (join equivalence class) and one "private"
    variable per relation that consolidates all of its non-join attributes. A relation *R* has the variable set
    *V_R* (its join variables plus its private variable). The statistics translate into degree constraints as
    follows:

    - the l1 norm of ``deg_R(*|X)`` is the cardinality constraint ``log2 ||deg_R(V_R|∅)||_1 <= log2 |R|``
    - all other norms are ``log2 ||deg_R(V_R|X)||_p <= log2 ||deg_R(*|X)||_p``

    This mirrors the reference implementation (`LpFlow/flow_bound.cpp` and its use in
    `benchmarks/experiments/lpbase_lpflow_lpberge_comparison.py`).

    Usage: create the LP from the incidence graph, add the statistics constraints, finalize and compute the bound.
    There are no explicit additivity constraints, since these are implied by the flow formulation. If any relation is
    known to be empty (i.e., all of its norms are zero), the bound is 0 without solving the LP.

    Notes
    -----
    Implementation generated by Claude Opus 5.5 (Anthropic), instructed and supervised by Rico Bergmann.
    """

    def __init__(self, incidence_graph: IncidenceGraph) -> None:
        self._graph = incidence_graph
        self._relations = sorted(
            (node for node, kind in incidence_graph.nodes(data="bipartite") if kind == "relation"), key=_sort_key
        )
        join_vars = sorted(
            (node for node, kind in incidence_graph.nodes(data="bipartite") if kind == "variable"), key=_sort_key
        )
        self._col_to_var: dict[pb.ColumnReference, frozenset] = {col: var for var in join_vars for col in var}

        # The LP variables of each relation, V_R. They are the "target" variables that must each receive a unit flow.
        self._rel_vars: dict[pb.TableReference, _FlowNode] = {}
        for rel in self._relations:
            members = {("private", rel)} | {("join", var) for var in incidence_graph.neighbors(rel)}
            self._rel_vars[rel] = frozenset(members)
        self._targets = [("join", var) for var in join_vars] + [("private", rel) for rel in self._relations]

        self._dcs: list[_DegreeConstraint] = []
        self._empty_result = False

        self._objective: np.ndarray | None = None
        self._A_ub: scipy.sparse.csr_array | None = None
        self._b_ub: np.ndarray | None = None
        self._bounds: list[tuple[float | None, float | None]] | None = None

    def add_statistics_constraints(self, statistics: Mapping[pb.ColumnReference, LpNorms]) -> Self:
        """Translates the norms of the full and simple degree sequences ``deg_R(*|X)`` into degree constraints.

        The l0 norm (number of distinct values) is not used, just like in `LpBerge`. Statistics on columns that are
        not part of the join graph are ignored.
        """
        for col, norms in statistics.items():
            if not pb.ColumnReference.assert_bound(col):
                raise pb.UnboundColumnError(col)

            join_var = self._col_to_var.get(col)
            if join_var is None:
                continue

            if norms.is_zero():
                # The (filtered) relation is empty, hence the entire join result is empty. log2(0) is undefined, so we
                # must not add the constraint to the LP but rather short-circuit the bound computation.
                self._empty_result = True
                continue

            rel_vars = self._rel_vars[col.table]
            cond = frozenset({("join", join_var)})

            for p, norm in norms.norms.items():
                if norm <= 0:
                    self._empty_result = True
                    continue
                if p < 1:
                    raise ValueError(f"Norm l{p} is not supported by LPflow (only p >= 1 or p = inf)")

                if p == 1:
                    # 1/1 h(X) + h(V_R|X) = h(V_R), i.e. the l1 norm is just the cardinality of R
                    dc = _DegreeConstraint(frozenset(), rel_vars, 1.0, float(np.log2(norm)))
                else:
                    dc = _DegreeConstraint(cond, rel_vars, float(p), float(np.log2(norm)))
                self._dcs.append(dc)

        return self

    def finalize(self) -> Self:
        """Builds the flow network and assembles the LP. No more constraints can be added afterwards."""
        edges = self._build_flow_network()
        nodes = {frozenset({target}) for target in self._targets}
        nodes |= {node for edge in edges for node in edge}
        nodes = sorted((node for node in nodes if node), key=lambda node: sorted(map(str, node)))  # skip the source

        forward_capacities: dict[_FlowEdge, list[tuple[int, float]]] = collections.defaultdict(list)
        for i, dc in enumerate(self._dcs):
            # w_i * h(Y|X): capacity of X -> Y
            if dc.cond != dc.target:
                forward_capacities[(dc.cond, dc.target)].append((i, 1.0))
            # w_i/p * h(X): capacity of ∅ -> X
            if not np.isinf(dc.p) and dc.cond:
                forward_capacities[(frozenset(), dc.cond)].append((i, 1.0 / dc.p))

        # LP variables: first the weights w_i of the degree constraints, then one flow per (target, edge)
        n_dcs, n_edges = len(self._dcs), len(edges)

        def flow_idx(t: int, e: int) -> int:
            return n_dcs + t * n_edges + e

        n_lp_vars = n_dcs + len(self._targets) * n_edges

        # Forward edges (X ⊂ Y) can carry negative flow, which corresponds to the infinite-capacity backward direction.
        # Backward edges (Y ⊃ X) only carry non-negative flow and do not have a capacity.
        is_forward = [len(src) < len(dst) for src, dst in edges]
        bounds: list[tuple[float | None, float | None]] = [(0, None)] * n_dcs
        for _ in self._targets:
            bounds.extend((None, None) if forward else (0, None) for forward in is_forward)

        rows, cols, vals, rhs = [], [], [], []
        n_rows = 0

        for t, target in enumerate(self._targets):
            # Flow conservation: inflow - outflow >= demand, i.e. outflow - inflow <= -demand
            conservation_row = {node: n_rows + i for i, node in enumerate(nodes)}
            n_rows += len(nodes)
            for node in nodes:
                rhs.append(-1.0 if node == frozenset({target}) else 0.0)

            for e, (src, dst) in enumerate(edges):
                if src:
                    rows.append(conservation_row[src])
                    cols.append(flow_idx(t, e))
                    vals.append(1.0)
                if dst:
                    rows.append(conservation_row[dst])
                    cols.append(flow_idx(t, e))
                    vals.append(-1.0)

            # Capacities of the forward edges: f_t(X -> Y) - sum_i coeff_i * w_i <= 0
            for e, edge in enumerate(edges):
                if not is_forward[e]:
                    continue
                rows.append(n_rows)
                cols.append(flow_idx(t, e))
                vals.append(1.0)
                for dc_idx, coeff in forward_capacities[edge]:
                    rows.append(n_rows)
                    cols.append(dc_idx)
                    vals.append(-coeff)
                rhs.append(0.0)
                n_rows += 1

        objective = np.zeros(n_lp_vars)
        objective[:n_dcs] = [dc.log_bound for dc in self._dcs]

        self._objective = objective
        self._A_ub = scipy.sparse.csr_array((vals, (rows, cols)), shape=(n_rows, n_lp_vars))
        self._b_ub = np.array(rhs)
        self._bounds = bounds
        return self

    def compute_bound(self) -> pb.Cardinality:
        """Solves the LP and computes the bound ``2^(sum_i w_i * b_i)``.

        Raises
        ------
        RuntimeError
            If the LP could not be solved. Typically, this happens if the LP is infeasible because some relation does
            not have any statistics constraints (and hence its variables cannot receive any flow).
        """
        if self._empty_result:
            return pb.Cardinality.zero()
        if self._objective is None:
            raise RuntimeError("LpFlow must be finalized before computing the bound")

        res = scipy.optimize.linprog(
            self._objective, A_ub=self._A_ub, b_ub=self._b_ub, bounds=self._bounds, method="highs"
        )
        if res.status != 0:
            raise RuntimeError(f"Could not solve LPflow: {res.message}")

        return pb.Cardinality(float(np.exp2(res.fun)))

    def _build_flow_network(self) -> list[_FlowEdge]:
        """Determines the edges of the flow network, mirroring ``LpNormLP::construct_flow_network`` of the reference.

        An edge is skipped if its opposite edge already exists. In this case, the (forward) edge represents both
        directions through negative flows.
        """
        edges: dict[_FlowEdge, None] = {}  # insertion-ordered set

        def add_edge(src: _FlowNode, dst: _FlowNode) -> None:
            if src != dst and (dst, src) not in edges:
                edges[(src, dst)] = None

        empty: _FlowNode = frozenset()
        for dc in self._dcs:
            add_edge(dc.cond, dc.target)
            if not np.isinf(dc.p):
                add_edge(empty, dc.cond)
        for dc in self._dcs:
            add_edge(dc.target, empty)
            for var in dc.target:
                add_edge(dc.target, frozenset({var}))

        return list(edges)
